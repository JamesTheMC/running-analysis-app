"""Build js/presentation/evidence.js from reference/corrections-evidence.json (verified literature).

    python3 tools/build_evidence.py

Keeps, per finding, each suggestion's cue, type, strength, caveats and its evidence (short
citation, link, design, result, verified flag). Run again whenever the JSON is updated.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = json.load(open(os.path.join(ROOT, "reference", "corrections-evidence.json")))


def short(citation):
    m = re.match(r"\s*([A-Za-z\-' ]+?)[ ,].*?((?:19|20)\d\d)", citation)
    return f"{m.group(1).strip()} {m.group(2)}" if m else citation[:40]


def link(e):
    if e.get("doi"):
        return "https://doi.org/" + e["doi"]
    if e.get("pmid"):
        return f"https://pubmed.ncbi.nlm.nih.gov/{e['pmid']}/"
    return e.get("url")


out = {}
for key, f in src["findings"].items():
    out[key] = {
        "notes": f.get("notes", ""),
        "suggestions": [
            {
                "cue": s["cue"],
                "type": s["type"],
                "strength": s["strength"],
                "caveats": s.get("caveats", ""),
                "evidence": [
                    {"short": short(e["citation"]), "citation": e["citation"], "url": link(e), "design": e.get("design", ""), "result": e.get("result", ""), "verified": bool(e.get("verified"))}
                    for e in s.get("evidence", [])
                ],
            }
            for s in f["suggestions"]
        ],
    }

header = (
    "// GENERATED by tools/build_evidence.py from reference/corrections-evidence.json. Do not edit.\n"
    f"// Literature search: {src.get('searched', '')[:200]}\n"
)
body = "export const EVIDENCE = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
body += "export const UNVERIFIED = " + json.dumps(src.get("unverified", []), indent=1, ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "js", "presentation", "evidence.js"), "w").write(header + body)
print("wrote js/presentation/evidence.js:", {k: len(v["suggestions"]) for k, v in out.items()})
