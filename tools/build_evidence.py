"""Build js/presentation/evidence.js from reference/corrections-evidence.json (verified literature).

    python3 tools/build_evidence.py

Keeps, per finding, each suggestion's cue, type, strength, caveats and its evidence (short
citation, link, design, result, verified flag). Run again whenever the JSON is updated.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = json.load(open(os.path.join(ROOT, "reference", "corrections-evidence.json")))


def short(citation):
    m = re.match(r"\s*([A-Za-z\-' ]+?)[ ,].*?((?:19|20)\d\d)", citation)
    return f"{m.group(1).strip()} {m.group(2)}" if m else citation[:40]


def link(e):
    if e.get("doi"):
        return "https://doi.org/" + e["doi"]
    if e.get("pmid"):
        return f"https://pubmed.ncbi.nlm.nih.gov/{e['pmid']}/"
    return e.get("url")


out = {}
for key, f in src["findings"].items():
    out[key] = {
        "notes": f.get("notes", ""),
        "suggestions": [
            {
                "cue": s["cue"],
                "type": s["type"],
                "strength": s["strength"],
                "caveats": s.get("caveats", ""),
                "evidence": [
                    {"short": short(e["citation"]), "citation": e["citation"], "url": link(e), "design": e.get("design", ""), "result": e.get("result", ""), "verified": bool(e.get("verified"))}
                    for e in s.get("evidence", [])
                ],
            }
            for s in f["suggestions"]
        ],
    }

header = (
    "// GENERATED by tools/build_evidence.py from reference/corrections-evidence.json. Do not edit.\n"
    f"// Literature search: {src.get('searched', '')[:200]}\n"
)
body = "export const EVIDENCE = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
body += "export const UNVERIFIED = " + json.dumps(src.get("unverified", []), indent=1, ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "js", "presentation", "evidence.js"), "w").write(header + body)
print("wrote js/presentation/evidence.js:", {k: len(v["suggestions"]) for k, v in out.items()})

# --- Limitations chains (reference/limitations-evidence.json) -> js/presentation/limitations.js ---
lim = json.load(open(os.path.join(ROOT, "reference", "limitations-evidence.json")))


def ev_list(items):
    return [{"short": short(e.get("citation", "")), "url": link(e), "pmid": str(e.get("pmid") or ""), "result": e.get("result", ""), "design": e.get("design", ""), "verified": bool(e.get("verified", True))} for e in (items or [])]


chains = {}
for key, c in lim["chains"].items():
    chains[key] = {
        "findings": c.get("findings", []),
        "strength": c.get("strength", "none"),
        "notes": c.get("notes", ""),
        "limitations": [{"name": x["name"], "strength": x.get("link_strength", "none"), "note": x.get("note", ""), "evidence": ev_list(x.get("evidence"))} for x in c.get("limitations", [])],
        "compensations": [{"text": x["text"], "strength": x.get("link_strength", "none"), "evidence": ev_list(x.get("evidence"))} for x in c.get("compensations", [])],
        "screens": [{"name": x["name"], "how": x.get("how", ""), "positiveIf": x.get("positive_if", ""), "evidence": ev_list(x.get("evidence"))} for x in c.get("screens", [])],
        "work": [
            {"item": x["item"], "type": x.get("type", ""), "dose": x.get("dose", ""), "doseSource": x.get("dose_source", ""), "changesRunning": x.get("changes_running_pattern", ""), "priority": x.get("priority", 9), "evidence": ev_list(x.get("evidence"))}
            for x in c.get("work", [])
        ],
    }

# Every PMID verified in either file: citations shown in the app must come from this list (tested).
pmids = set()
for f in src["findings"].values():
    for s in f["suggestions"]:
        for e in s.get("evidence", []):
            if e.get("pmid"):
                pmids.add(str(e["pmid"]))
for c in lim["chains"].values():
    for sect in ("limitations", "compensations", "screens", "work"):
        for x in c.get(sect, []):
            for e in x.get("evidence", []) or []:
                if e.get("pmid"):
                    pmids.add(str(e["pmid"]))

header2 = "// GENERATED by tools/build_evidence.py from reference/limitations-evidence.json. Do not edit.\n"
body2 = "export const CHAINS = " + json.dumps(chains, indent=1, ensure_ascii=False) + ";\n"
body2 += "export const VERIFIED_PMIDS = " + json.dumps(sorted(pmids)) + ";\n"
body2 += "export const LIMITATIONS_UNVERIFIED = " + json.dumps(lim.get("unverified", []), indent=1, ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "js", "presentation", "limitations.js"), "w").write(header2 + body2)
print("wrote js/presentation/limitations.js:", len(chains), "chains,", len(pmids), "verified PMIDs")
